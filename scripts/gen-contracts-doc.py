#!/usr/bin/env python3
"""Writes the contracts list of a deployment from its manifest, broadcast, rolled series and configs.

    python3 scripts/gen-contracts-doc.py <network>   (run by scripts/markets.sh wire)
    monad-testnet → deployments/testnet-contracts.md; monad-mainnet → deployments/mainnet-contracts.md
"""
import datetime
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEP = os.path.join(ROOT, "deployments")
NETWORK = sys.argv[1] if len(sys.argv) > 1 else "monad-testnet"
man = json.load(open(os.path.join(DEP, f"{NETWORK}.json")))
CHAIN = man["chainId"]
config = json.load(open(os.path.join(DEP, "config", f"{NETWORK}.json")))
TESTNET = CHAIN != 143
NAME = "Monad testnet" if TESTNET else "Monad mainnet"
EXPLORER = "https://testnet.monadvision.com" if TESTNET else "https://monadvision.com"
OUT = os.path.join(DEP, ("testnet" if TESTNET else "mainnet") + "-contracts.md")
bc = json.load(open(os.path.join(ROOT, f"contract/broadcast/Deploy.s.sol/{CHAIN}/run-latest.json")))
series_path = os.path.join(DEP, f"{NETWORK}.series.json")
series = json.load(open(series_path))["series"] if os.path.exists(series_path) else []

created = {t["contractName"]: t["contractAddress"] for t in bc["transactions"] if t["transactionType"] == "CREATE"}
src = lambda a: f"[Sourcify](https://repo.sourcify.dev/{CHAIN}/{a})"
exp = lambda a: f"[MonadVision]({EXPLORER}/address/{a})"
code = lambda a: f"`{a}`"
cfgs = {}
for s in series:
    if s["listing"] not in cfgs:
        cfgs[s["listing"]] = json.load(open(os.path.join(DEP, "config", f"{NETWORK}.{s['listing']}.json")))

L = [
    f"# Optara contracts on {NAME}",
    "",
    f"Every contract of the current {NAME} deployment, with links to its verified source. Regenerated by "
    "`scripts/markets.sh wire`; previous deployments are archived in `deployments/archive/`.",
    "",
    "| | |",
    "|---|---|",
    f"| Network | {NAME} (chain ID {CHAIN}) |",
    f"| Deployed at block | {man['deployedAtBlock']:,} |",
    f"| Deployer (holds no rights) | `{man['deployer']}` |",
    f"| Roles (governance, guardian, admins) | `{man['roles']['governance']}` |",
    f"| Machine-readable manifest | [`{NETWORK}.json`]({NETWORK}.json) |",
    "",
    "## Verification",
    "",
    "Every contract below is source-verified on [Sourcify](https://sourcify.dev) and on MonadVision's Sourcify "
    "(status `match`; `exact_match` is impossible because the build sets `bytecode_hash = \"none\"`). Option tokens "
    "are EIP-1167 clones of the verified `ExternalOptionWrapper`; Kuru order books are Kuru's own contracts.",
    "",
    "## Core protocol",
    "",
    "Use the **proxy** address. The ProxyAdmin, owned by UpgradeAdmin, is the only account that can upgrade it.",
    "",
    "| Contract | Proxy (use this) | Implementation | ProxyAdmin |",
    "|---|---|---|---|",
]
for name, p in sorted(man["proxies"].items()):
    L.append(
        f"| {name} | {code(p['proxy'])}<br>{src(p['proxy'])} · {exp(p['proxy'])} | {code(p['implementation'])}<br>{src(p['implementation'])} "
        f"| {code(p['proxyAdmin'])}<br>{src(p['proxyAdmin'])} |"
    )
L += ["", "## Governance, venues and templates", "", "| Contract | Address | Role |", "|---|---|---|"]
ua, ka, w = man["upgradeAdmin"], man["kuruAdapter"], created.get("ExternalOptionWrapper", "")
L.append(f"| UpgradeAdmin | {code(ua)}<br>{src(ua)} · {exp(ua)} | Timelocked upgrades for every proxy |")
L.append(f"| KuruAdapter | {code(ka)}<br>{src(ka)} · {exp(ka)} | Routes buys and sells to Kuru order books |")
if w:
    L.append(f"| ExternalOptionWrapper (template) | {code(w)}<br>{src(w)} · {exp(w)} | ERC-20 template cloned for each option |")
for f in man.get("extra", {}).get("testnetFeeds", []):
    L.append(
        f"| TestnetPushFeed ({f['label']}) | {code(f['feed'])}<br>{src(f['feed'])} · {exp(f['feed'])} | "
        "**Testnet only**: settlement price, pushed by the keeper from Pyth every 5 min |"
    )

by_listing = {}
for s in series:
    by_listing.setdefault(s["listing"], []).append(s)
for listing, rows in by_listing.items():
    c = cfgs[listing]
    size = int(c["contractSizeWad"]) / 1e18
    L += [
        "",
        f"## Options: {c['underlyingSymbol']}/{c['assetSymbol']}",
        "",
        f"Contract size {size:g} {c['underlyingSymbol']}, cash-settled in {c['assetSymbol']} (`{c['asset']}`)."
        + (" Each option trades on its own Kuru book." if any(r["kuruMarket"] != "0x0000000000000000000000000000000000000000" for r in rows) else " Kuru books: pending."),
        "",
        "| Option | Expiry (UTC) | Option token | Kuru book |",
        "|---|---|---|---|",
    ]
    for s in sorted(rows, key=lambda r: (r["expiry"], int(r["strikeWad"]), r["type"])):
        k = int(s["strikeWad"]) / 1e18
        when = datetime.datetime.fromtimestamp(s["expiry"], datetime.timezone.utc).strftime("%d %b %H:%M")
        L.append(
            f"| {c['underlyingSymbol']} {k:,.4g} {s['type'].title()} | {when} | {code(s['wrapper'])}<br>{exp(s['wrapper'])} "
            f"| {code(s['kuruMarket'])}<br>{exp(s['kuruMarket'])} |"
        )
ext = [("Kuru Router", config.get("kuruRouter")), ("Pyth", config.get("pyth"))]
seen = set()
for c in cfgs.values():
    for label, a in ((f"{c['underlyingSymbol']} (underlying)", c["underlying"]), (f"{c['assetSymbol']} (settlement asset)", c["asset"])):
        if a.lower() not in seen:
            seen.add(a.lower()); ext.append((label, a))
L += ["", "## External dependencies (not deployed by Optara)", "", "| Contract | Address |", "|---|---|"]
L += [f"| {n} | `{a}` |" for n, a in ext if a and int(a, 16) != 0]
L.append("")
open(OUT, "w").write("\n".join(L))
print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(series)} options)", file=sys.stderr)
