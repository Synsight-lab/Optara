import { chromium } from "playwright";
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const t0 = Date.now();
p.on("console", (m) => console.log("console", m.type(), m.text().slice(0, 200)));
p.on("request", (r) => { if (!/\.(js|css|svg|woff2?)$/.test(r.url())) console.log(Date.now() - t0, "req", r.url().slice(0, 90), (r.postData() ?? "").slice(0, 90)); });
p.on("response", async (r) => { if (r.url().includes("monad")) { const t = await r.text().catch(() => ""); console.log(Date.now() - t0, "res", r.status(), t.slice(0, 160)); } });
await p.goto(process.argv[2]); await p.waitForTimeout(12000);
console.log("HERO:", (await p.locator("section.card").first().innerText()).replace(/\n/g, " | "));
await b.close();
